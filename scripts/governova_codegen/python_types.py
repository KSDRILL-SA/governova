def _manifest() -> str:
    """The generated package's `pyproject.toml`.

    Versioned by `SCHEMA_VERSION` rather than independently: this package *is* the
    schema, so a consumer pinning `governova-types` is pinning the index shape it
    can read. An independent version number would be a second thing to remember
    to bump, and it would drift.

    `pydantic` is the only dependency — deliberately not `governova`, so consuming
    the types never drags in the build tooling.
    """
    return f'''# DO NOT EDIT. Generated by `governova-codegen`.
# Version tracks SCHEMA_VERSION in scripts/governova_compile/schema.py.
[project]
name = "governova-types"
version = "{SCHEMA_VERSION}"
description = "Typed models for the Governova compiled constitutional index"
readme = "README.md"
requires-python = ">=3.12"
authors = [{{ name = "Maluleke Kurhula Success" }}]
license = {{ text = "MIT" }}
classifiers = [
    "Development Status :: 3 - Alpha",
    "Intended Audience :: Developers",
    "License :: OSI Approved :: MIT License",
    "Programming Language :: Python :: 3.12",
    "Typing :: Typed",
]
dependencies = ["pydantic>=2.9"]

[project.urls]
Homepage = "https://github.com/KSDRILL-SA/governova"

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = ["governova_types"]
'''


_README = f"""# governova-types

Typed models for the Governova compiled constitutional index
(`compiled/constitution.json`).

**Generated — do not edit.** Emitted from
`scripts/governova_compile/schema.py` by `governova-codegen`. Edit the schema,
re-run codegen.

The version tracks the index schema version (currently `{SCHEMA_VERSION}`): pinning
this package pins the index shape your code can read.

```python
from governova_types import CompiledIndex

index = CompiledIndex.model_validate_json(Path("compiled/constitution.json").read_text())
```

Depends only on `pydantic` — never on the Governova engine.
"""


def generate_python_types(schema_source: Path, types_py_root: Path) -> Path:
    """Emit the complete `governova-types` distribution. Returns the models path."""
    pkg = types_py_root / "governova_types"
    pkg.mkdir(parents=True, exist_ok=True)

    source = schema_source.read_text(encoding="utf-8")
    # Replace the original module docstring (first triple-quoted block) with the banner.
    body = _strip_leading_docstring(source)
    (pkg / "models.py").write_text(_BANNER + "\n" + body, encoding="utf-8")
    (pkg / "__init__.py").write_text(_INIT, encoding="utf-8")
    # A typed package that ships no marker is untyped to its consumers (S1.49).
    (pkg / "py.typed").write_text("", encoding="utf-8")
    (types_py_root / "pyproject.toml").write_text(_manifest(), encoding="utf-8")
    (types_py_root / "README.md").write_text(_README, encoding="utf-8")
    return pkg / "models.py"


def generated_files(types_py_root: Path) -> dict[Path, str]:
    """Every path this generator owns, mapped to its expected content.

    Used by `--check` to detect drift without writing anything. Kept beside the
    writer so a new emitted file cannot be added without appearing here.
    """
    pkg = types_py_root / "governova_types"
    return {
        pkg / "__init__.py": _INIT,
        pkg / "py.typed": "",
        types_py_root / "pyproject.toml": _manifest(),
        types_py_root / "README.md": _README,
    }


def _strip_leading_docstring(source: str) -> str:
    """Remove the module-level docstring so the banner replaces it cleanly."""
    stripped = source.lstrip()
    if stripped.startswith('"""'):
        end = stripped.find('"""', 3)
        if end != -1:
            return stripped[end + 3 :].lstrip("\n")
    return source
