"""Generate the standalone `governova_types` Python package from schema.py.

The published `governova-types` package must not depend on the build tooling
(`governova`, the engine distribution). So we vendor the schema models into it:
read schema.py, prepend a generated-file banner, and write it as
`governova_types/models.py`. The schema remains the single source of truth —
codegen propagates it.

**A complete distribution, not just modules.** The generated tree is a uv
workspace member and is intended for PyPI, so it needs a `pyproject.toml` and a
`py.typed` marker. Emitting only the modules left a member directory uv could not
resolve, which broke `uv sync` for anyone who had run codegen — invisible in CI,
because a fresh checkout has no such directory at all.

**Everything emitted here is deterministic.** No timestamps, no commit SHAs,
sorted exports. The output is committed and drift-checked in CI exactly like
`compiled/constitution.json`, and a generator whose output varies between runs
cannot be drift-checked.
"""

